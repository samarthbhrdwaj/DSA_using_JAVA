package JAVA_02_IfElse;
public class JAVA_01_RelationalOp {
    static void main() {
        int a = 10, b = 20;
        System.out.println(a>b);
        System.out.println(a>=b);
        System.out.println(a<b);
        System.out.println(a<=b);
        System.out.println(a==b);
        System.out.println(a!=b);
    }
}