package JAVA_01_Basics;
public class JAVA_04_ArithmeticOp {
    static void main() {
        int x = 5, y = 2;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);

        double a = 5, b = 2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
    }
}