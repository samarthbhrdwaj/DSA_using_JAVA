package JAVA_05_Methods;
public class JAVA_01_BuiltInMath {
    static void main() {
        System.out.println(Math.max(1, 2));
        System.out.println(Math.min(1, 2));
        System.out.println(Math.sqrt(20));
        System.out.println(Math.cbrt(20));
        System.out.println(Math.floor(-5.5));
        System.out.println(Math.ceil(-5.5));
        System.out.println(Math.abs(-96));
        System.out.println(Math.pow(8, 3));
    }
}